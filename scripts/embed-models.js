// Turns the .glb files in assets/models into ES modules under
// src/renderer/models (gzipped, then base64), so the renderer can parse them
// without fetch (file:// URLs in Electron and the inlined web demo both work).
// Gzip shrinks these box-built models ~8x. Run after adding or changing a model.
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const root = path.join(__dirname, '..');
const from = path.join(root, 'assets', 'models');
const to = path.join(root, 'src', 'renderer', 'models');
fs.mkdirSync(to, { recursive: true });
for (const f of fs.readdirSync(from).filter((n) => n.endsWith('.glb'))) {
  const name = f.replace(/\.glb$/, '');
  const id = name.toUpperCase().replace(/[^A-Z0-9]+/g, '_') + '_GLB';
  const b64 = zlib.gzipSync(fs.readFileSync(path.join(from, f)), { level: 9 }).toString('base64');
  fs.writeFileSync(path.join(to, `${name}.js`), `// Generated by scripts/embed-models.js from assets/models/${f} (gzip + base64). Do not edit.\nexport const ${id} = '${b64}';\n`);
  console.log(`embed-models: ${f} -> src/renderer/models/${name}.js (${b64.length} chars)`);
}
